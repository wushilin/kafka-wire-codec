#![allow(unused_variables, clippy::manual_range_contains)]

use bytes::Bytes;
use crate::codec::*;
use crate::error::DecodeError;

#[derive(Debug, Clone, Default)]
pub struct TopicPartitions {
    /// The topic ID.
    pub topic_id: [u8; 16],
    /// The partitions.
    pub partitions: Vec<i32>,
    /// Raw tagged fields (flexible versions), in ascending tag order.
    pub tagged_fields: Vec<(u32, Bytes)>,
}

impl TopicPartitions {
    pub fn encoded_size(&self, version: i16) -> usize {
        let mut size = 0usize;
        {
            size += 16;
        }
        {
            { let arr = &self.partitions;
                size += uvarint_size(arr.len() as u64 + 1);
                size += arr.len() * 4;
            }
        }
        size += tagged_fields_size(&self.tagged_fields);
        size
    }

    pub fn encode<B: WireBuf>(&self, version: i16, buf: &mut B) {
        {
            put_uuid(buf, &self.topic_id);
        }
        {
            { let arr = &self.partitions;
                put_uvarint(buf, arr.len() as u64 + 1);
                for item in arr { put_i32(buf, *item); }
            }
        }
        put_tagged_fields(buf, &self.tagged_fields);
    }

    pub fn decode(version: i16, buf: &mut Bytes) -> Result<Self, DecodeError> {
        let mut msg = TopicPartitions::default();
        {
            msg.topic_id = get_uuid(buf)?;
        }
        {
            let len_opt = { let n = get_uvarint32(buf)?; if n == 0 { None } else { Some((n - 1) as usize) } };
            let count = len_opt.ok_or(DecodeError::NullForNonNullable)?;
            { let mut items = Vec::with_capacity(count.min(buf.len()));
                for _ in 0..count { items.push(get_i32(buf)?); }
            msg.partitions = items; }
        }
        msg.tagged_fields = get_tagged_fields(buf)?;
        Ok(msg)
    }
}

/// Valid versions: 0-1.
#[derive(Debug, Clone)]
pub struct ConsumerGroupHeartbeatRequest {
    /// The group identifier.
    pub group_id: Bytes,
    /// The member id generated by the consumer. The member id must be kept during the entire lifetime of the consumer process.
    pub member_id: Bytes,
    /// The current member epoch; 0 to join the group; -1 to leave the group; -2 to indicate that the static member will rejoin.
    pub member_epoch: i32,
    /// null if not provided or if it didn't change since the last heartbeat; the instance Id otherwise.
    pub instance_id: Option<Bytes>,
    /// null if not provided or if it didn't change since the last heartbeat; the rack ID of consumer otherwise.
    pub rack_id: Option<Bytes>,
    /// -1 if it didn't change since the last heartbeat; the maximum time in milliseconds that the coordinator will wait on the member to revoke its partitions otherwise.
    pub rebalance_timeout_ms: i32,
    /// null if it didn't change since the last heartbeat; the subscribed topic names otherwise.
    pub subscribed_topic_names: Option<Vec<Bytes>>,
    /// null if it didn't change since the last heartbeat; the subscribed topic regex otherwise.
    pub subscribed_topic_regex: Option<Bytes>,
    /// null if not used or if it didn't change since the last heartbeat; the server side assignor to use otherwise.
    pub server_assignor: Option<Bytes>,
    /// null if it didn't change since the last heartbeat; the partitions owned by the member.
    pub topic_partitions: Option<Vec<TopicPartitions>>,
    /// Raw tagged fields (flexible versions), in ascending tag order.
    pub tagged_fields: Vec<(u32, Bytes)>,
}

impl Default for ConsumerGroupHeartbeatRequest {
    fn default() -> Self {
        Self {
            group_id: Bytes::new(),
            member_id: Bytes::new(),
            member_epoch: 0,
            instance_id: None,
            rack_id: None,
            rebalance_timeout_ms: -1,
            subscribed_topic_names: None,
            subscribed_topic_regex: None,
            server_assignor: None,
            topic_partitions: None,
            tagged_fields: Vec::new(),
        }
    }
}

impl ConsumerGroupHeartbeatRequest {
    pub const API_KEY: i16 = 68;
    pub const VALID_MIN_VERSION: i16 = 0;
    pub const VALID_MAX_VERSION: i16 = 1;
    /// First flexible (tagged-fields) version; `i16::MAX` if never flexible.
    pub const FLEXIBLE_MIN_VERSION: i16 = 0;

    pub fn encoded_size(&self, version: i16) -> usize {
        assert!((Self::VALID_MIN_VERSION..=Self::VALID_MAX_VERSION).contains(&version),
            "unsupported version {} for api key {}", version, Self::API_KEY);
        let mut size = 0usize;
        {
            size += compact_string_size(&self.group_id);
        }
        {
            size += compact_string_size(&self.member_id);
        }
        {
            size += 4;
        }
        {
            size += compact_nullable_string_size(self.instance_id.as_deref());
        }
        {
            size += compact_nullable_string_size(self.rack_id.as_deref());
        }
        {
            size += 4;
        }
        {
            match &self.subscribed_topic_names {
                Some(arr) => {
                size += uvarint_size(arr.len() as u64 + 1);
                for item in arr {
                    size += compact_string_size(item);
                }
                }
                None => {
                    size += 1;
                }
            }
        }
        if version >= 1 {
            size += if version >= 1 { compact_nullable_string_size(self.subscribed_topic_regex.as_deref()) } else { let v = self.subscribed_topic_regex.as_deref().expect("field subscribed_topic_regex is None but not nullable at this version"); compact_string_size(v) };
        }
        {
            size += compact_nullable_string_size(self.server_assignor.as_deref());
        }
        {
            match &self.topic_partitions {
                Some(arr) => {
                size += uvarint_size(arr.len() as u64 + 1);
                for item in arr {
                    size += item.encoded_size(version);
                }
                }
                None => {
                    size += 1;
                }
            }
        }
        size += tagged_fields_size(&self.tagged_fields);
        size
    }

    pub fn encode<B: WireBuf>(&self, version: i16, buf: &mut B) {
        assert!((Self::VALID_MIN_VERSION..=Self::VALID_MAX_VERSION).contains(&version),
            "unsupported version {} for api key {}", version, Self::API_KEY);
        {
            put_compact_string(buf, &self.group_id);
        }
        {
            put_compact_string(buf, &self.member_id);
        }
        {
            put_i32(buf, self.member_epoch);
        }
        {
            put_compact_nullable_string(buf, self.instance_id.as_deref());
        }
        {
            put_compact_nullable_string(buf, self.rack_id.as_deref());
        }
        {
            put_i32(buf, self.rebalance_timeout_ms);
        }
        {
            match &self.subscribed_topic_names {
                Some(arr) => {
                put_uvarint(buf, arr.len() as u64 + 1);
                for item in arr { put_compact_string(buf, item); }
                }
                None => {
                    put_uvarint(buf, 0);
                }
            }
        }
        if version >= 1 {
            if version >= 1 { put_compact_nullable_string(buf, self.subscribed_topic_regex.as_deref()) } else { let v = self.subscribed_topic_regex.as_deref().expect("field subscribed_topic_regex is None but not nullable at this version"); put_compact_string(buf, v) };
        }
        {
            put_compact_nullable_string(buf, self.server_assignor.as_deref());
        }
        {
            match &self.topic_partitions {
                Some(arr) => {
                put_uvarint(buf, arr.len() as u64 + 1);
                for item in arr { item.encode(version, buf); }
                }
                None => {
                    put_uvarint(buf, 0);
                }
            }
        }
        put_tagged_fields(buf, &self.tagged_fields);
    }

    pub fn decode(version: i16, buf: &mut Bytes) -> Result<Self, DecodeError> {
        if !(Self::VALID_MIN_VERSION..=Self::VALID_MAX_VERSION).contains(&version) {
            return Err(DecodeError::UnsupportedVersion { api_key: Self::API_KEY, version });
        }
        let mut msg = ConsumerGroupHeartbeatRequest::default();
        {
            msg.group_id = (get_compact_string(buf)?).ok_or(DecodeError::NullForNonNullable)?;
        }
        {
            msg.member_id = (get_compact_string(buf)?).ok_or(DecodeError::NullForNonNullable)?;
        }
        {
            msg.member_epoch = get_i32(buf)?;
        }
        {
            msg.instance_id = get_compact_string(buf)?;
        }
        {
            msg.rack_id = get_compact_string(buf)?;
        }
        {
            msg.rebalance_timeout_ms = get_i32(buf)?;
        }
        {
            let len_opt = { let n = get_uvarint32(buf)?; if n == 0 { None } else { Some((n - 1) as usize) } };
            msg.subscribed_topic_names = match len_opt {
                Some(count) => {
                let mut items = Vec::with_capacity(count.min(buf.len()));
                for _ in 0..count { items.push((get_compact_string(buf)).and_then(|o| o.ok_or(DecodeError::NullForNonNullable))?); }
                Some(items)
                }
                None => None,
            };
        }
        if version >= 1 {
            msg.subscribed_topic_regex = { let v = get_compact_string(buf)?; if version >= 1 { v } else { Some(v.ok_or(DecodeError::NullForNonNullable)?) } };
        }
        {
            msg.server_assignor = get_compact_string(buf)?;
        }
        {
            let len_opt = { let n = get_uvarint32(buf)?; if n == 0 { None } else { Some((n - 1) as usize) } };
            msg.topic_partitions = match len_opt {
                Some(count) => {
                let mut items = Vec::with_capacity(count.min(buf.len()));
                for _ in 0..count { items.push(TopicPartitions::decode(version, buf)?); }
                Some(items)
                }
                None => None,
            };
        }
        msg.tagged_fields = get_tagged_fields(buf)?;
        Ok(msg)
    }
}

impl crate::Encodable for ConsumerGroupHeartbeatRequest {
    const API_KEY: i16 = 68;
    const VALID_MIN_VERSION: i16 = 0;
    const VALID_MAX_VERSION: i16 = 1;
    const FLEXIBLE_MIN_VERSION: i16 = 0;
    fn wire_size(&self, version: i16) -> usize { self.encoded_size(version) }
    fn write(&self, version: i16, buf: &mut bytes::BytesMut) { self.encode(version, buf) }
    fn read(version: i16, buf: &mut Bytes) -> Result<Self, DecodeError> { Self::decode(version, buf) }
}

impl crate::EncodableZeroCopy for ConsumerGroupHeartbeatRequest {
    fn write_segmented(&self, version: i16, buf: &mut SegmentedBuf) { self.encode(version, buf) }
}
